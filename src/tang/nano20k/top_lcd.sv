// state machine handling kickstart upload from Companion
reg [2:0]	 kick_upload_state = 3'd0;
reg		     kick_is_256k; 
assign	     rom_download_in_progress = kick_upload_state >= 3'd1 && kick_upload_state <= 3'd3;
   
wire		 rom_data_available;   
wire [7:0]	 rom_data;
